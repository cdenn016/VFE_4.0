gens = []
# arc-preserving map: within the arc of each node, shift by one grid step cyclically inside the arc
arcs = {+1: [m for m in range(Mc) if np.sign(np.cos(2*np.pi*(m+0.5)/Mc)) > 0],
        -1: [m for m in range(Mc) if np.sign(np.cos(2*np.pi*(m+0.5)/Mc)) < 0]}
def arc_shift(m):
    s = 1 if m in arcs[1] else -1
    a = arcs[s]
    return a[(a.index(m) + 1) % len(a)]
half = {m: (m + Mc // 2) % Mc for m in range(Mc)}  # half-period shift reverses the sign
for v in range(M):
    cmap = np.array([index[tuple(np.where(np.arange(M) == v, [arc_shift(x) for x in vv], vv))] for vv in vals])
    gens.append((cmap, np.arange(N)))
# node elements: reverse sigma_w by a half-period shift, exchange mirror coordinates
def node_circle(w):
    cmap_coin, pi = node_element_coin(d, w, paths, np.array(list(itertools.product([1, -1], repeat=M)), float))
    # rebuild cell map for the circle: theta'_w = theta_w + pi; theta'_{mirror v} = theta_v
    Lc, Rc = 2 * w + 1, 2 * w + 2
    mir = {}
    if w == 0:
        mir = {1: 2, 2: 1}
    cm = np.zeros(C, dtype=int)
    for n, vv in enumerate(vals):
        new = vv.copy()
        new[w] = half[vv[w]]
        for a, b in mir.items():
            new[b] = vv[a]
        cm[n] = index[tuple(new)]
    return cm, pi
for w in range(M):
    gens.append(node_circle(w))
dim, null = fixed_space_dim(d, gens, N, C)
Lc = lift_image(d, spc)
