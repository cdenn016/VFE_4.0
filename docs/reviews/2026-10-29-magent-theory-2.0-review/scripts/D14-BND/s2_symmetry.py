# ----------------------------------------------------------------------------- (f) labeling bijection
for d in (2, 3):
    N, M, paths = tree(d)
    sp = make_space(d, np.array([1.0]), "coin", orient=np.ones((1, M)))
    labelings = {tuple(sp.uidx[:, 0, n]) for n in range(len(sp.Uc))}
    # every labeling must be a tree automorphism: common-prefix length preserved
    U = all_bits(d)
    def cpl(a, b):
        k = 0
        while k < d and a[k] == b[k]:
            k += 1
        return k
    ok = True
    for lab in labelings:
        for i in range(N):
            for j in range(N):
                if i != j:
                    from bnd_common import lca_class
                    if cpl(U[lab[i]], U[lab[j]]) != lca_class(paths, i, j):
                        ok = False
    print(f"(f) d={d}: distinct labelings = {len(labelings)} (|Aut(T_d)| = 2^(N-1) = {2**(N-1)}); all are automorphisms: {ok}")
