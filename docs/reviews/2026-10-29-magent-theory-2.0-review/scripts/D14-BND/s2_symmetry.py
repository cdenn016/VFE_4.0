# circle d=2 with a 4-point circle: add sign-preserving cyclic shifts within each half-circle arc
d = 2; Mc = 4
N, M, paths = tree(d)
spc = make_space(d, np.array([1.0]), "circle", Mc=Mc, alpha=np.zeros((1, M)))
