# ----------------------------------------------------------------------------- (d) Phi_tau
def random_aut(d, rng):
    """tau encoded by flip c(prefix) in {-1,1} for every prefix of length 0..d-1."""
    return {p: rng.choice([-1, 1]) for j in range(d) for p in itertools.product([1, -1], repeat=j)}

def apply_tau(tau, u):
    out = []
    for j in range(len(u)):
        out.append(tau[tuple(u[:j])] * u[j])
    return tuple(out)

d = 3
N, M, paths = tree(d)
orient = rng.choice([-1.0, 1.0], size=(1, M))
sp = make_space(d, np.array([1.0]), "coin", orient=orient)
vals = sp.vals.astype(int)
index = {tuple(v): n for n, v in enumerate(vals)}
U = all_bits(d)
worst = 0
tau = random_aut(d, rng)
# node v's prefix: bits of any leaf below it; use the path of the leftmost descendant leaf
def node_prefix(v, sigma):
    path = []
    node = v
    while node > 0:
        p = (node - 1) // 2
        path.append((p, 1 if node == 2 * p + 1 else -1))
        node = p
    path.reverse()
    return tuple(e * sigma[p] for (p, e) in path)
cells_image = set()
for n, c in enumerate(vals):
    sigma = c * orient[0]
    new = c.copy()
    for v in range(M):
        pre = node_prefix(v, sigma)
        if tau[pre] == -1:
            new[v] = -c[v]
    n2 = index[tuple(new)]
    cells_image.add(n2)
    for i in range(N):
        u_old = U[sp.uidx[i, 0, n]]
        u_new = U[sp.uidx[i, 0, n2]]
        worst = max(worst, int(u_new != apply_tau(tau, u_old)))
print(f"(d) Phi_tau (coin, d=3, random orientations, random tau): mismatches of u(i,Phi_tau xi) vs tau u(i,xi): {worst}; "
      f"bijective on cells: {len(cells_image) == len(vals)}")

