# ----------------------------------------------------------------------------- (a)
def equivariance_check(d):
    N, M, paths, FD, PD = setup(d, 2, 2, rng)
    lam = FD.spq.A[:, None] * FD.spq.Uc[None, :]
    mu = FD.sps.A[:, None] * FD.sps.Uc[None, :]
    C = len(FD.spq.Uc)
    q = np.exp(0.5 * rng.normal(size=(N, 2, C)))
    s = np.exp(0.5 * rng.normal(size=(N, 2, C)))
    for i in range(N):
        q[i] /= np.sum(lam * q[i]); s[i] /= np.sum(mu * s[i])
    beta = np.zeros((N, N)); gamma = np.zeros((N, N))
    for i in range(N):
        beta[i, FD.edges[i]] = rng.dirichlet(np.ones(N - 1))
        gamma[i, FD.edges[i]] = rng.dirichlet(np.ones(N - 1))
    perm = rng.permutation(N)
    cq = [rng.permutation(C) for _ in range(2)]      # fibered: one cell permutation per base point
    cs = [rng.permutation(C) for _ in range(2)]

    def act(x):
        q, s, b, g = x
        q2 = np.stack([np.stack([q[perm[i], r, cq[r]] for r in range(2)]) for i in range(N)])
        s2 = np.stack([np.stack([s[perm[i], w, cs[w]] for w in range(2)]) for i in range(N)])
        b2 = b[np.ix_(perm, perm)]; g2 = g[np.ix_(perm, perm)]
        return (q2, s2, b2, g2)
    x = (q, s, beta, gamma)
    lhs = fine_velocity(act(x), FD)
    rhs = act(fine_velocity(x, FD))
    return max(np.max(np.abs(a - b)) for a, b in zip(lhs, rhs))


print("(a) equivariance of the fine field at random non-family states, random fibered maps x agent perms")
for d in (2, 3):
    print(f"   d={d}: sup |F(omega x) - omega F(x)| = {equivariance_check(d):.2e}")

# ----------------------------------------------------------------------------- (b), (c)
def node_element_coin(d, w, paths, vals):
    """(Phi_w, pi_w) on the coin realization with orientation +1: returns (cell map, leaf perm)."""
    N = 2 ** d; M = N - 1
    # subtree nodes below w: map node in left subtree <-> same relative position in right subtree
    def descend(node, rel):
        for e in rel:
            node = 2 * node + (1 if e == 1 else 2)
        return node
    def rel_path(node, top):
        rel = []
        while node != top:
            p = (node - 1) // 2
            rel.append(1 if node == 2 * p + 1 else -1)
            node = p
        return rel[::-1]
    def below(node, top):
        while node > top:
            node = (node - 1) // 2
            if node == top:
                return True
        return False
    L, R = 2 * w + 1, 2 * w + 2
    # node map on internal and leaf nodes (mirror by translation)
    def mirror(node):
        if node == L or below(node, L):
            return descend(R, rel_path(node, L))
        if node == R or below(node, R):
            return descend(L, rel_path(node, R))
        return node
    pi = np.array([mirror(M + i) - M for i in range(N)])
    # cell map: theta'_w = -theta_w ; theta'_{mirror(v)} = theta_v for v strictly below w
    C = vals.shape[0]
    index = {tuple(v): n for n, v in enumerate(vals.astype(int))}
    cmap = np.zeros(C, dtype=int)
    for n, v in enumerate(vals.astype(int)):
        new = v.copy()
        new[w] = -v[w]
        for node in range(M):
            if mirror(node) != node:
                new[mirror(node)] = v[node]
        cmap[n] = index[tuple(new)]
    return cmap, pi


def fixed_space_dim(d, generators, N, C):
    """Dimension of {x in R^{N x C}: x_i(c) = x_{pi(i)}(cmap(c)) for all generators}."""
    n = N * C
    rows = []
    for cmap, pi in generators:
        Mx = np.zeros((n, n))
        for i in range(N):
            for c in range(C):
                Mx[i * C + c, pi[i] * C + cmap[c]] += 1.0
        rows.append(Mx - np.eye(n))
    S = np.vstack(rows)
    sv = np.linalg.svd(S, compute_uv=False)
    dim = n - int(np.sum(sv > 1e-9))
    # null space basis
    _, s, Vt = np.linalg.svd(S)
    null = Vt[np.sum(s > 1e-9):]
    return dim, null


def lift_image(d, sp):
    N = 2 ** d
    cols = []
    for k in range(2 ** d):
        f = np.zeros((1, 2 ** d)); f[0, k] = 1.0
        cols.append(lift(f, sp).reshape(-1))
    return np.array(cols)


