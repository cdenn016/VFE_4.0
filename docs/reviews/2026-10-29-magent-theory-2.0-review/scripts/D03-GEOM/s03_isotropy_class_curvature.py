"""D03-GEOM s03: minimizing connection class with NONZERO infinitesimal isotropy.

G = U(2) acting linearly on two complex location laws CN(psi_i, I) on C^2
(Fisher metric on means proportional to the Euclidean metric of R^8).
Section over R^4: psi1(c) with norm R constant, psi2 = z(c) psi1(c).
Stabilizer of the pair is the U(1) generated by i(I - psihat psihat^dagger), so
J has constant rank 3 and ker J is one-dimensional (geo:shape-pullback, which
assumes ker J = 0, does not apply).  Checks:
 (0) structure identity geo:structure-identity (convention check, all pairs);
 (1) J F is the same for two minimizing representatives A and A + beta (beta
     stabilizer-valued with c-dependent direction), on ALL coordinate pairs;
 (2) the full curvature F differs between the two representatives;
 (3) J F(Z, .) = 0 for Z in the radical of h^min, and J F restricted to the
     radical is zero (so J F on the radical carries no information);
 (4) J F is nonzero on some pair (the class curvature is nontrivial);
 (5) L_Z h^min = 0 for a radical field Z (basicness) and the bracket of two
     radical fields stays in the radical (involutivity);
 (6) control: a non-minimizing connection changes J F.
Derivatives of the section are exact (sympy); derivatives of A, h, Z use a
fourth-order central difference with step 1e-3.
"""
import numpy as np
import sympy as sp

c = sp.symbols('c1:5', real=True)
R = 1.3
u1 = 1 + 0.3*c[0] + 0.2*c[2]**2 + sp.I*(0.5*c[3] + 0.1*c[1])
u2 = 0.4 + 0.3*c[2]*c[3] + sp.I*(0.7*c[1] - 0.2*c[0])
nrm = sp.sqrt(sp.re(u1)**2 + sp.im(u1)**2 + sp.re(u2)**2 + sp.im(u2)**2)
psi1 = [R*u1/nrm, R*u2/nrm]
phi1 = c[0] + 0.3*c[2]**2 + 0.2*c[1]*c[3]
phi2 = c[1] + 0.2*sp.sin(c[3]) + 0.1*c[0]*c[2]
z = phi1 + sp.I*phi2
psi2 = [z*psi1[0], z*psi1[1]]
comps = [psi1[0], psi1[1], psi2[0], psi2[1]]
preal = []
for w in comps:
    preal += [sp.re(sp.expand_complex(w)), sp.im(sp.expand_complex(w))]
P = sp.Matrix(preal)
dP = P.jacobian(sp.Matrix(c))
f_p = sp.lambdify([c], P, 'numpy')
f_dp = sp.lambdify([c], dP, 'numpy')

I2 = np.eye(2, dtype=complex)
sig = [np.array([[0, 1], [1, 0]], complex), np.array([[0, -1j], [1j, 0]]), np.array([[1, 0], [0, -1]], complex)]
E = [1j*I2] + [1j*s for s in sig]
def mat(a): return sum(a[k]*E[k] for k in range(4))
def coef(M): return np.array([np.real(np.trace(Ek.conj().T @ M))/2 for Ek in E])
def cvec(v8): return np.array([v8[0] + 1j*v8[1], v8[2] + 1j*v8[3]]), np.array([v8[4] + 1j*v8[5], v8[6] + 1j*v8[7]])
def rvec(a, b): return np.array([a[0].real, a[0].imag, a[1].real, a[1].imag, b[0].real, b[0].imag, b[1].real, b[1].imag])
def act(M, v8):
    a, b = cvec(v8)
    return rvec(M @ a, M @ b)
def Jmat(p8):
    return np.column_stack([act(Ek, p8) for Ek in E])
def stab_coef(p8):
    a, _ = cvec(p8)
    ph = a/np.linalg.norm(a)
    return coef(1j*(I2 - np.outer(ph, ph.conj())))

def beta(x):
    return np.array([np.sin(x[0]) + 0.5, x[1]*x[2], 0.3 - x[3]**2, np.cos(x[0]*x[3])])
def gam(x):
    return np.array([0.2 + 0.1*x[1], -0.3*x[0], 0.15, 0.25*x[2]])

def A_rep(cv, rep):
    p8 = np.array(f_p(cv), float).ravel()
    dp = np.array(f_dp(cv), float)
    Jm = Jmat(p8)
    A = np.array([-np.linalg.pinv(Jm, rcond=1e-10) @ dp[:, mu] for mu in range(4)])
    if rep == 1:
        A = A + np.outer(beta(cv), stab_coef(p8))
    if rep == 2:
        A = A + np.outer(gam(cv), np.array([0, 1.0, 0, 0]))
    return A

def V_of(cv, rep):
    p8 = np.array(f_p(cv), float).ravel()
    dp = np.array(f_dp(cv), float)
    A = A_rep(cv, rep)
    Jm = Jmat(p8)
    return np.array([dp[:, mu] + Jm @ A[mu] for mu in range(4)])

hstep = 1e-3
def deriv(fun, cv, nu):
    e = np.zeros(4)
    e[nu] = hstep
    return (-fun(cv + 2*e) + 8*fun(cv + e) - 8*fun(cv - e) + fun(cv - 2*e))/(12*hstep)

c0 = np.array([0.21, -0.17, 0.33, 0.12])
p0 = np.array(f_p(c0), float).ravel()
J0 = Jmat(p0)
print("rank J at c0:", np.linalg.matrix_rank(J0, tol=1e-9), " |J stab| =", np.linalg.norm(J0 @ stab_coef(p0)))

def curvature(rep):
    A = A_rep(c0, rep)
    dA = [deriv(lambda cv: A_rep(cv, rep), c0, nu) for nu in range(4)]
    F = np.zeros((4, 4, 4))
    for mu in range(4):
        for nu in range(4):
            Fm = mat(dA[mu][nu] - dA[nu][mu]) + (mat(A[mu]) @ mat(A[nu]) - mat(A[nu]) @ mat(A[mu]))
            F[mu, nu] = coef(Fm)
    return A, F

A0, F0 = curvature(0)
A1, F1 = curvature(1)
A2, F2 = curvature(2)
def JF(F):
    return np.array([[J0 @ F[m, n] for n in range(4)] for m in range(4)])
JF0, JF1, JF2 = JF(F0), JF(F1), JF(F2)

V0 = V_of(c0, 0)
dV = [deriv(lambda cv: V_of(cv, 0), c0, nu) for nu in range(4)]
res = 0.0
for mu in range(4):
    for nu in range(4):
        rhs = (dV[mu][nu] + act(mat(A0[mu]), V0[nu])) - (dV[nu][mu] + act(mat(A0[nu]), V0[mu])) - JF0[mu, nu]
        res = max(res, np.max(np.abs(rhs)))
print("(0) structure-identity residual (all pairs, V([d_mu,d_nu]) = 0):", f"{res:.2e}")
print("(1) max |J F(A) - J F(A+beta)| over all pairs:", f"{np.max(np.abs(JF0 - JF1)):.2e}",
      " vs max |J F| =", f"{np.max(np.abs(JF0)):.3f}")
print("(2) max |F(A) - F(A+beta)| (full curvature):", f"{np.max(np.abs(F0 - F1)):.3f}")

h0 = V0 @ V0.T
w, U = np.linalg.eigh(h0)
print("    eigenvalues of h^min at c0:", np.array2string(w, precision=4))
K = U[:, w < 1e-8]
print("    radical dimension:", K.shape[1])
JFZ = max(np.max(np.abs(np.einsum('m,mnk->nk', K[:, i], JF0))) for i in range(K.shape[1]))
print("(3) max |J F(Z, d_nu)| for Z in radical:", f"{JFZ:.2e}")
JFKK = np.einsum('mi,nj,mnk->ijk', K, K, JF0)
print("    max |J F| on radical x radical:", f"{np.max(np.abs(JFKK)):.2e}")
print("(4) J F(d_1, d_2) =", np.array2string(JF0[0, 1], precision=4), " norm", f"{np.linalg.norm(JF0[0, 1]):.4f}")
phase = J0 @ np.array([1.0, 0, 0, 0])
cosang = abs(phase @ JF0[0, 1])/(np.linalg.norm(phase)*np.linalg.norm(JF0[0, 1]))
print("    |cos angle| between J F(d1,d2) and phase orbit direction J(iI):", f"{cosang:.6f}")

z0 = np.array([0.3, -0.7, 0.5, 0.9])
z1 = np.array([-0.4, 0.2, 0.8, -0.1])
def hmin(cv):
    V = V_of(cv, 0)
    return V @ V.T
def Zf(cv, zz):
    h = hmin(cv)
    return (np.eye(4) - h @ np.linalg.pinv(h, rcond=1e-8)) @ zz
Z0 = Zf(c0, z0)
dh = [deriv(hmin, c0, l) for l in range(4)]
dZ = [deriv(lambda cv: Zf(cv, z0), c0, l) for l in range(4)]
LZh = np.zeros((4, 4))
for m in range(4):
    for n in range(4):
        LZh[m, n] = sum(Z0[l]*dh[l][m, n] for l in range(4)) + sum(h0[l, n]*dZ[m][l] + h0[m, l]*dZ[n][l] for l in range(4))
print("(5) max |L_Z h^min| =", f"{np.max(np.abs(LZh)):.2e}", " vs max |h^min| =", f"{np.max(np.abs(h0)):.3f}",
      " |Z| =", f"{np.linalg.norm(Z0):.3f}")
Z1 = Zf(c0, z1)
dZ1 = [deriv(lambda cv: Zf(cv, z1), c0, l) for l in range(4)]
brk = sum(Z0[l]*dZ1[l] - Z1[l]*dZ[l] for l in range(4))
print("    |r([Z0,Z1])| =", f"{np.linalg.norm(V0.T @ brk):.2e}", " vs |[Z0,Z1]| =", f"{np.linalg.norm(brk):.3f}")
ctrl = max(np.max(np.abs(np.einsum('m,mnk->nk', K[:, i], JF2))) for i in range(K.shape[1]))
print("(6) control non-minimizing A: max |J F - J F(A)| =", f"{np.max(np.abs(JF2 - JF0)):.3f}",
      "; max |J F(Z,.)| =", f"{ctrl:.3f}")
