"""GAP09-S1 s5: (A) Dobrushin's partition supremum (Gray 1990, Lemma 5.2.2) behind the Borel
measurability of KL on Prob x Prob; (B) the non-dominated clause of imem:history-theorem.

(A) KL(N(0,1) || N(0.5, 2)) against finite partitions generated by the countable field of dyadic
    intervals (cells of width 2^-k on [-L, L] plus two tails): the partition sums increase with
    refinement to the closed form.  For P = delta_0 against M = N(0,1) (not dominated) the sums
    over the same field diverge.
(B) Gaussian protocol with a noiseless speaker sensor D_1 = X_1, deterministic result Y_1 = X_1
    and identity encoder: the message is H = D_1, its kernel delta_{d_1} has no density with
    respect to the predictive law N(0, v1), and the update is the disintegration Gamma_0(. | D_1 = h).
    With encoder noise R (dominated case) the receiver posterior of X_0 given (D_0, H) converges to
    that disintegration as R -> 0, while the message density k(h|d_1) = N(h; d_1, R) has no limit
    as a function.
"""
import numpy as np
from scipy.stats import norm

# (A)
m1, v1, m2, v2 = 0.0, 1.0, 0.5, 2.0
kl_exact = 0.5 * (v1 / v2 + (m1 - m2) ** 2 / v2 - 1 + np.log(v2 / v1))
print('(A) closed-form KL(N(0,1)||N(0.5,2)) = %.12f' % kl_exact)
L = 16.0
prev = -np.inf
for k in [0, 2, 4, 6, 8, 10, 12, 14]:
    edges = np.concatenate(([-np.inf], np.arange(-L, L + 1e-12, 2.0 ** -k), [np.inf]))
    P = np.diff(norm.cdf(edges, m1, np.sqrt(v1))); M = np.diff(norm.cdf(edges, m2, np.sqrt(v2)))
    msk = P > 0
    H = float(np.sum(P[msk] * np.log(P[msk] / M[msk])))
    print('    width 2^-%-2d: partition sum = %.12f   (nondecreasing: %s)' % (k, H, H >= prev - 1e-15))
    prev = H
for k in [0, 4, 8, 16, 32]:
    # cell containing 0 is [0, 2^-k); P = delta_0 puts mass one on it
    Mcell = norm.cdf(2.0 ** -k) - norm.cdf(0.0)
    print('    delta_0 vs N(0,1), cell width 2^-%-2d: partition sum = %.4f' % (k, np.log(1.0 / Mcell)))

# (B)
rho, N0 = 0.7, 0.5          # corr(X0, X1); receiver sensor noise variance; unit cue variances
C = np.array([[1.0, rho], [rho, 1.0]])


def receiver_posterior(R):
    # variables (X0, X1, D0, H) with D0 = X0 + e0, H = X1 + eta, eta ~ N(0, R)
    A = np.array([[1, 0], [0, 1], [1, 0], [0, 1]], float)
    S = A @ C @ A.T
    S[2, 2] += N0
    S[3, 3] += R
    obs = [2, 3]
    Soo = S[np.ix_(obs, obs)]; S0o = S[0, obs]
    gain = np.linalg.solve(Soo, S0o)
    return gain, S[0, 0] - S0o @ gain


# disintegration: condition X0 on (D0, X1) exactly
Sx = np.array([[1.0 + N0, rho], [rho, 1.0]]); s0 = np.array([1.0, rho])
gain_dis = np.linalg.solve(Sx, s0); var_dis = 1.0 - s0 @ gain_dis
print('(B) disintegration Gamma(. | D0, D1 = h): gain on (d0, h) = (%.10f, %.10f), variance = %.10f' % (*gain_dis, var_dis))
for R in [1.0, 1e-2, 1e-4, 1e-8, 1e-12]:
    g, v = receiver_posterior(R)
    print('    encoder noise R = %-6g: gain = (%.10f, %.10f), variance = %.10f, sup_h k(h|d1) = %.3e'
          % (R, g[0], g[1], v, 1 / np.sqrt(2 * np.pi * R)))
